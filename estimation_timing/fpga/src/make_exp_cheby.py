#!/usr/bin/env python3
"""Generate a degree-12 exponential with a tail cutoff and physical-energy fixed types."""
import argparse
import json
import math
from pathlib import Path

import numpy as np
from scipy.special import ive


def size_config(n, beta, eps_b, cutoff):
    m = n * (n + 1) // 2
    frac = max(0, math.ceil(math.log2(beta * m / math.log1p(2 * eps_b))))
    max_delta = 2 * math.ceil(n * math.sqrt(n) / math.sqrt(math.pi))
    # The sign bit is included; positive max_delta must be representable exactly.
    integer = max_delta.bit_length() + 1
    # Round upward so the discarded exponential tail stays within its budget.
    cut = math.ceil(math.ldexp(cutoff, frac)) / 2**frac
    # SK coefficients satisfy ||c||_2=sqrt(n). Flipping k spins changes k(n+1-k) terms.
    changed = ((n + 1) ** 2) // 4
    delta_bound = 2 * math.sqrt(n * changed) + changed / 2**frac
    partial_bound = math.sqrt(n * m) + m / 2**(frac + 1)
    if delta_bound > max_delta or partial_bound >= 2 ** (integer - 1):
        raise ValueError(f"Requested integer bound is insufficient at n={n}")
    if cut >= 32:
        raise ValueError("Exponential interval exceeds the polynomial type's integer range")
    return dict(n=n, m=m, frac=frac, int_bits=integer, word_bits=frac + integer,
                max_delta=max_delta, cutoff_energy=cut,
                rounding_tv_bound=math.expm1(beta * m / 2**frac) / 2)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--beta", type=float, required=True)
    parser.add_argument("--degree", type=int, required=True)
    parser.add_argument("--eps-b", type=float, required=True)
    parser.add_argument("--eps-op", type=float, required=True)
    parser.add_argument("--test-n", type=int, required=True)
    parser.add_argument("--sizes", type=int, nargs="+", required=True)
    args = parser.parse_args()
    if args.beta <= 0 or args.degree < 1 or not 0 < args.eps_b < 1 or not 0 < args.eps_op < 1:
        parser.error("Positive beta/degree and error budgets in (0,1) are required")
    if min([args.test_n, *args.sizes]) < 8 or max([args.test_n, *args.sizes]) > 64:
        parser.error("The configured SK bound/testbenches support 8 <= n <= 64")

    tau = math.log(2 / args.eps_op)
    k = np.arange(args.degree + 1)
    # exp(-u), u in [0,tau], with Chebyshev variable y=2u/tau-1.
    coefficients = 2 * (-1.0)**k * ive(k, tau / 2)
    coefficients[0] /= 2
    omitted_tail = max(0.0, 1.0 - float(np.abs(coefficients).sum()))
    if omitted_tail + 1e-14 > args.eps_op / 2:
        raise ValueError("Degree is too small for the polynomial portion of the requested budget")
    sizes = sorted(set([args.test_n, *args.sizes]))
    configs = [size_config(n, args.beta, args.eps_b, tau / args.beta) for n in sizes]

    Path("src").mkdir(exist_ok=True)
    header = ["#pragma once", "// Generated by src/make_exp_cheby.py; inputs are physical energies.",
              f"static const int POLY_DEGREE = {args.degree};",
              f"static const double BETA = {args.beta:.17g};",
              f"static const double EPS_B = {args.eps_b:.17g};",
              f"static const double EPS_OP = {args.eps_op:.17g};",
              "static const energy_t EXP_E_CUT = energy_t(EXP_CUT_VALUE);",
              f"static const poly_t EXP_Y_SLOPE = poly_t({2 * args.beta / tau:.17g});",
              "static const poly_t CHEB_COEFFS[POLY_DEGREE + 1] = {"]
    header += [f"    poly_t({c:.17g})," for c in coefficients]
    Path("src/exp_cheby.hpp").write_text("\n".join([*header, "};", ""]))
    fixed = ["#pragma once", "// Generated: FRAC rounds physical Hamiltonian coefficients.",
             "#ifndef SK_N", '#error "Compile with -DSK_N=<configured size>"', "#endif"]
    for index, cfg in enumerate(configs):
        fixed += [f"#{'if' if index == 0 else 'elif'} SK_N == {cfg['n']}",
                  f"#define FRAC {cfg['frac']}", f"#define INT_BITS {cfg['int_bits']}",
                  f"#define MAX_DELTA_ENERGY {cfg['max_delta']}",
                  f"#define EXP_CUT_VALUE {cfg['cutoff_energy']:.17g}"]
    fixed += ["#else", '#error "SK_N is not in this run; regenerate the headers"', "#endif", ""]
    Path("src/fixed_config.hpp").write_text("\n".join(fixed))
    config = dict(beta=args.beta, degree=args.degree, eps_b=args.eps_b, eps_op=args.eps_op,
                  test_n=args.test_n, synthesis_sizes=args.sizes, tau=tau,
                  polynomial_tail_bound=omitted_tail, sizes=configs)
    Path("build").mkdir(exist_ok=True)
    Path("build/run_config.json").write_text(json.dumps(config, indent=2) + "\n")
    print(f"Generated exponential: beta={args.beta:g}, degree={args.degree}, cutoff={tau / args.beta:.9g}")
    print(f"Polynomial truncation bound={omitted_tail:.3g}; tail budget={args.eps_op / 2:.3g}")
    print(" n    M   fractional  integer  total  max|delta|  rounding TV bound")
    for cfg in configs:
        print(f"{cfg['n']:2d} {cfg['m']:4d} {cfg['frac']:10d} {cfg['int_bits']:8d} "
              f"{cfg['word_bits']:6d} {cfg['max_delta']:11d} {cfg['rounding_tv_bound']:18.8g}")


if __name__ == "__main__":
    main()
